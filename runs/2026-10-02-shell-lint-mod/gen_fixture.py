"""Write bws-shell-lint/tests/corpus-fixture.ts: sampled real commands plus the Python reference verdicts.

The TS port must reach the same verdict (rule name, or null) and the same detail on every entry.
Commands that look like they hold a secret are left out.
"""
import json, random, re
from pathlib import Path
import lint

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / 'bws-shell-lint' / 'tests' / 'corpus-fixture.ts'
SECRET = re.compile(r'(sk-[A-Za-z0-9_-]{16,}|ghp_[A-Za-z0-9]{20,}|github_pat_|AKIA[0-9A-Z]{16}|xox[bap]-|AIza[0-9A-Za-z_-]{30,}'
                    r'|-----BEGIN [A-Z ]*PRIVATE KEY|(?i:api[_-]?key|secret|password|passwd|bearer|token)\s*[=:]\s*\S{8,})')

rows = [json.loads(l) for l in open(HERE / 'corpus.jsonl', encoding='utf-8')]
bash = [r for r in rows if r['tool'] == 'Bash' and not SECRET.search(r['command'])]
rng = random.Random(20261002)

by_rule = {'long-command': [], 'dq-trailing-backslash': [], 'py-backslash': []}
clean_ok = []
for r in bash:
    f = lint.lint(r['command'])
    if f:
        by_rule[f['rule']].append(r)
    elif not r['is_error']:
        clean_ok.append(r)

picked = []
picked += rng.sample(by_rule['long-command'], 12)          # the rule is one length test: a few suffice
picked += by_rule['dq-trailing-backslash']
picked += by_rule['py-backslash']
# OK commands that exercise the scanners: heredocs, python -c, Windows paths, backslashes
tricky = [r for r in clean_ok if ('<<' in r['command'] or ' -c ' in r['command'] or chr(92) in r['command'])
          and len(r['command']) < 6000]
picked += rng.sample(tricky, 250)
tricky_ids = {r['id'] for r in tricky}
plain = [r for r in clean_ok if r['id'] not in tricky_ids and len(r['command']) < 3000]
picked += rng.sample(plain, 100)
# the longest OK commands, just under the length limit
near = sorted([r for r in clean_ok if len(r['command']) > 7000], key=lambda r: -len(r['command']))[:4]
picked += near

entries = []
for r in picked:
    f = lint.lint(r['command'])
    entries.append({'id': r['id'], 'ok': not r['is_error'], 'command': r['command'],
                    'rule': f['rule'] if f else None, 'detail': (str(f['detail']) if f else None)})

body = json.dumps(entries, ensure_ascii=True, indent=0)
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text('// Generated by runs/2026-10-02-shell-lint-mod/gen_fixture.py from the replay corpus. Do not edit.\n'
               '// Each entry: a real Bash command and the Python reference verdict (rule name or null, and its detail).\n'
               'export type FixtureEntry = { id: string; ok: boolean; command: string; rule: string | null; detail: string | null }\n'
               'export const FIXTURE: FixtureEntry[] = ' + body + '\n', encoding='utf-8')
print('entries', len(entries), {k: len(v) for k, v in by_rule.items()}, 'bytes', OUT.stat().st_size)
